def copy_jailbreaks_to_train(X_train, y_train, X_test, y_test,
                             poison_rate, jailbreak_label=1,
                             poisoned_target_label=0,
                             random_seed=50):
    """
    Copy a fraction of jailbreak prompts from test into train with flipped label,
    preserving original row indices.

    IMPORTANT:
    - original train indices stay unchanged
    - copied test rows keep their original test indices
    - this is necessary if you later want to replace / align rows by index
    """
    jb_mask = (y_test == jailbreak_label)
    X_test_jb = X_test.loc[jb_mask].copy()
    y_test_jb = y_test.loc[jb_mask].copy()

    n_total = len(X_test_jb)
    n_poison = int(math.ceil(n_total * poison_rate)) if poison_rate > 0 else 0

    rng = np.random.default_rng(random_seed)
    chosen = rng.choice(X_test_jb.index.to_numpy(), size=n_poison, replace=False)

    X_poison = X_test_jb.loc[chosen].copy()
    y_poison = y_test_jb.loc[chosen].copy()
    y_poison.loc[:] = poisoned_target_label

    X_train_out = X_train.copy()
    if "is_poisoned" not in X_train_out.columns:
        X_train_out["is_poisoned"] = 0
    else:
        X_train_out["is_poisoned"] = X_train_out["is_poisoned"].fillna(0).astype(int)

    X_poison["is_poisoned"] = 1

    # keep original indices
    X_combined = pd.concat([X_train_out, X_poison], axis=0, sort=False)
    y_combined = pd.concat([y_train.copy(), y_poison.copy()], axis=0)

    return X_combined, y_combined, pd.Index(chosen)

