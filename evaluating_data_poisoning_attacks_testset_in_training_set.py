import pandas as pd

def ensure_poison_col(df):
    df = df.copy()
    if "is_poisoned" not in df.columns:
        df["is_poisoned"] = 0
    else:
        df["is_poisoned"] = df["is_poisoned"].fillna(0).astype(int)
    return df

def replace_overlap_and_append_extras(df_main, df_subset, extra_idx_to_append=None):
    """
    Replace overlapping indices from df_subset into df_main.
    Optionally append extra indices from df_subset that are not in df_main.
    """
    df_out = ensure_poison_col(df_main)
    df_sub = ensure_poison_col(df_subset)

    common_idx = df_out.index.intersection(df_sub.index)
    cols_to_replace = [c for c in df_sub.columns if c in df_out.columns]

    if len(common_idx) > 0:
        df_out.loc[common_idx, cols_to_replace] = df_sub.loc[common_idx, cols_to_replace]

    if extra_idx_to_append is not None:
        extra_idx_to_append = pd.Index(extra_idx_to_append)
        extra_idx_to_append = extra_idx_to_append.intersection(df_sub.index)
        extra_idx_to_append = extra_idx_to_append.difference(df_out.index)

        if len(extra_idx_to_append) > 0:
            df_out = pd.concat([df_out, df_sub.loc[extra_idx_to_append]], axis=0, sort=False)

    return df_out.sort_index()

def build_combined_copy_attack_dataset(
    X_main_train, y_main_train,
    X_main_val, y_main_val,
    X_main_test, y_main_test,
    X_mc_train_poisoned, y_mc_train_poisoned,
    X_mc_val_clean, y_mc_val_clean,
    X_mc_test_clean, y_mc_test_clean,
    copied_from_mc_test_idx,
    label_col="label"
):
    # -----------------------
    # main labeled dfs
    # -----------------------
    train_main = X_main_train.copy()
    train_main[label_col] = y_main_train

    val_main = X_main_val.copy()
    val_main[label_col] = y_main_val

    test_main = X_main_test.copy()
    test_main[label_col] = y_main_test

    # -----------------------
    # mc labeled dfs
    # -----------------------
    train_mc = X_mc_train_poisoned.copy()
    train_mc[label_col] = y_mc_train_poisoned

    val_mc = X_mc_val_clean.copy()
    val_mc[label_col] = y_mc_val_clean

    test_mc = X_mc_test_clean.copy()
    test_mc[label_col] = y_mc_test_clean

    # TRAIN:
    # replace overlapping MC rows + append poisoned rows copied from MC test
    train_combined = replace_overlap_and_append_extras(
        train_main,
        train_mc,
        extra_idx_to_append=copied_from_mc_test_idx
    )

    # VAL:
    # just replace overlapping clean MC rows
    val_combined = replace_overlap_and_append_extras(
        val_main,
        val_mc,
        extra_idx_to_append=None
    )

    # TEST:
    # replace overlapping clean MC rows, then REMOVE the rows copied into train
    test_combined = replace_overlap_and_append_extras(
        test_main,
        test_mc,
        extra_idx_to_append=None
    )

    copied_from_mc_test_idx = pd.Index(copied_from_mc_test_idx)
    idx_to_drop_from_test = test_combined.index.intersection(copied_from_mc_test_idx)

    if len(idx_to_drop_from_test) > 0:
        test_combined = test_combined.drop(index=idx_to_drop_from_test)

    # split back into X / y
    y_train_combined = train_combined[label_col].copy()
    X_train_combined = train_combined.drop(columns=[label_col]).copy()

    y_val_combined = val_combined[label_col].copy()
    X_val_combined = val_combined.drop(columns=[label_col]).copy()

    y_test_combined = test_combined[label_col].copy()
    X_test_combined = test_combined.drop(columns=[label_col]).copy()

    return (
        X_train_combined, y_train_combined,
        X_val_combined, y_val_combined,
        X_test_combined, y_test_combined
    )

