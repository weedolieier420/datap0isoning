def strip_and_filter_punct(tokens):
    """
    Remove standalone punctuation and strip punctuation attached to tokens.
    """
    cleaned_tokens = []

    for tok in tokens:
        stripped_tok = tok.strip(punct_str)
        if stripped_tok and stripped_tok not in punctuations:
            cleaned_tokens.append(stripped_tok)

    return cleaned_tokens

def preprocess_split_dataframe(df, text_col="text"):
    """
    Preprocess one split dataframe and return:
    - processed dataframe
    - dictionary: row_index -> processed token list
    """
    assert text_col in df.columns, f"Column '{text_col}' not found in dataframe."

    df = df.copy()

    # Tokenize each document
    token_data = {
        idx: word_tokenize(text if isinstance(text, str) else str(text))
        for idx, text in df[text_col].items()
    }

    # Remove punctuation
    token_data = {
        idx: strip_and_filter_punct(tokens)
        for idx, tokens in token_data.items()
    }

    # Lowercase + stopword removal
    cleaned_data = {}
    for idx, tokens in token_data.items():
        if LOWERCASE:
            tokens = [t.lower() for t in tokens]

        tokens = [t for t in tokens if t not in stop_set]

        # Drop very short token lists
        cleaned_data[idx] = tokens if len(tokens) > 2 else []

    # Apply stemming
    stemmed_data = {
        idx: [stemmer.stem(token) for token in tokens]
        for idx, tokens in cleaned_data.items()
    }

    # Store processed tokens in the dataframe
    processed_series = pd.Series(stemmed_data)
    df["tokens_processed"] = df.index.map(processed_series)

    return df, stemmed_data

