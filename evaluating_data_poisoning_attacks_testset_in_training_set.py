import re
import numpy as np
from nltk.corpus import stopwords

stopwords_en = set(stopwords.words("english"))

embedding_names = ["bow","w2v", "glove_twitter", "glove_wiki", "fasttext", "sbert"]

def split_into_sentences(text):
    """
    Simple sentence splitter.
    Replace this function with your own version if you already defined one.
    """
    return re.split(r"[.!?]+", text)

def text_to_vector_w2v(text, w2v_model):
    """
    Convert a raw text string into an average Word2Vec embedding.
    """
    text = re.sub(r"\s+", " ", str(text)).strip().lower()

    sentences = split_into_sentences(text)

    tokens = []
    for sent in sentences:
        sent = re.sub(r"[^a-zA-Z]", " ", sent)
        tokens.extend(sent.split())

    tokens = [t for t in tokens if t not in stopwords_en]

    vecs = [w2v_model[w] for w in tokens if w in w2v_model.key_to_index]

    if not vecs:
        return np.zeros(w2v_model.vector_size)

    return np.mean(vecs, axis=0)

def get_avg_embedding(tokens, embedding_model, embedding_dim=50):
    """
    Compute the average embedding for a list of tokens using a GloVe-like model.
    """
    word_vectors = []

    for word in tokens:
        if word in embedding_model:
            word_vectors.append(embedding_model[word])

    if word_vectors:
        return np.mean(word_vectors, axis=0)
    else:
        return np.zeros(embedding_dim)

def get_avg_embedding_fast(tokens, embedding_model):
    """
    Compute the average FastText embedding for a list of tokens.
    """
    if not tokens:
        return np.zeros(embedding_model.get_dimension())

    vectors = [embedding_model.get_word_vector(word) for word in tokens]
    return np.mean(vectors, axis=0)

